export function filterExpertProfiles(
  kind: ExpertFilterKind,
  query = ''
): ExpertProfile[] {
  const tokens = query
    .trim()
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean);
  return EXPERT_PROFILES.filter((expert) => {
    const matchesKind = kind === 'all' || expert.roleKinds.includes(kind);
    if (!matchesKind) return false;
    if (tokens.length === 0) return true;

    const searchable = [
      expert.name,
      expert.shortRole,
      expert.institution,
      expert.region,
      expert.disciplines,
      expert.bio,
      expert.commissionMandate,
      expert.recommendedTrack,
      expert.recommendedRegion,
      ...expert.commissionDuties,
      ...expert.speakerTopics,
      ...expert.methodologicalModules,
    ]
      .join(' ')
      .toLowerCase();

    return tokens.every((token) => searchable.includes(token));
  });
}

export function getExpertCounts(): {
  all: number;
  commission: number;
  speaker: number;
} {
  return {
    all: EXPERT_PROFILES.length,
    commission: EXPERT_PROFILES.filter((e) => e.roleKinds.includes('commission')).length,
    speaker: EXPERT_PROFILES.filter((e) => e.roleKinds.includes('speaker')).length,
  };
}
